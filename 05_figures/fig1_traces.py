"""Fig 1: the four signal strips (Vm, Cai, CaSR, Cass of cell 2 over the whole data set) in the workflow diagram.

The rest of Fig 1 (boxes, arrows, LSTM cells) is a drawing, not generated by code.

    python3 05_figures/fig1_traces.py
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import _style  # noqa: E402,F401
from _style import plt  # noqa: E402
from common import ATTRS, load_dataset, out_dir, preprocess  # noqa: E402

data = preprocess(load_dataset().copy())  # the whole data set, z-scored
cell = 2
d = out_dir("05_figures")
np.savez_compressed(os.path.join(d, "fig1_traces.npz"), cell=cell, traces=data[:, cell, :])
for k, name in enumerate(ATTRS):
    plt.figure(figsize=(20, 1))
    plt.plot(range(data.shape[0]), data[:, cell, k], color="royalblue")
    ax = plt.gca()
    ax.set_xticks([])
    ax.set_yticks([])
    path = os.path.join(d, f"fig1_trace_{name}.png")
    plt.savefig(path, dpi=500)
    plt.close()
    print("wrote", os.path.relpath(path, os.path.dirname(os.path.dirname(d))))
